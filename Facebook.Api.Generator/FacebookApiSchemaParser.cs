    public class FacebookApiSchemaParser
    {
        public FacebookApiSchemaParser(Dictionary<String, List<MethodDefinition>> methodSignatures, CodeCommentStatement autoGeneratedComment)
        {
            this.MethodSignatures = methodSignatures;
            this.AutoGeneratedComment = autoGeneratedComment;
        }

        public Dictionary<String, List<MethodDefinition>> MethodSignatures { get; set; }
        public Dictionary<XmlQualifiedName, XmlSchemaType> BasicTypes { get; set; }
        public CodeCommentStatement AutoGeneratedComment { get; set; }

        public CodeCompileUnit[] Parse(TextReader codeStream)
        {
            XmlSchemaSet schemaSet = new XmlSchemaSet();            
            schemaSet.Add(XmlSchema.Read(codeStream, this.OnSchemaValidation));
            schemaSet.Compile();

            var compileUnits = new List<CodeCompileUnit>();

            this.BasicTypes = (
                from name in schemaSet.GlobalTypes.Names.OfType<XmlQualifiedName>()
                where schemaSet.GlobalTypes[name] is XmlSchemaType
                && !String.IsNullOrEmpty(((XmlSchemaType)schemaSet.GlobalTypes[name]).Name)
                select new
                {
                    Name = name,
                    Value = (XmlSchemaType)schemaSet.GlobalTypes[name]
                }).ToDictionary(type => type.Name, type => type.Value);
            compileUnits.AddRange(this.GenerateBasicTypeDeclarations());

            var classTypes = (
                from name in schemaSet.GlobalElements.Names.OfType<XmlQualifiedName>()
                where schemaSet.GlobalElements[name] is XmlSchemaElement
                && !String.IsNullOrEmpty(((XmlSchemaElement)schemaSet.GlobalElements[name]).Name)
                select new
                {
                    Name = name,
                    Value = (XmlSchemaElement)schemaSet.GlobalElements[name]
                }).ToDictionary(type => type.Name, type => type.Value);
            compileUnits.AddRange(this.GenerateClassDeclarations(classTypes));
            
            return compileUnits.ToArray();
        }

        public CodeNamespace GenerateCodeNamespace(String name)
        {
            var ns = new CodeNamespace(name);
            ns.Imports.AddRange(new CodeNamespaceImport[] {
                new CodeNamespaceImport("System"),
                new CodeNamespaceImport("System.Collections.Generic"),
                new CodeNamespaceImport("System.Xml.Linq"),
                new CodeNamespaceImport("Facebook")
            });
            ns.Comments.Add(this.AutoGeneratedComment);
            return ns;
        }

        public void OnSchemaValidation(Object sender, ValidationEventArgs e)
        {
            if (e.Severity == XmlSeverityType.Error) throw e.Exception;
            else Console.WriteLine(String.Format("XML Schema Warning: {0}", e.Exception.Message));
        }

        public IEnumerable<CodeCompileUnit> GenerateBasicTypeDeclarations()
        {
            var query =
                from complexType in this.BasicTypes.Values.OfType<XmlSchemaComplexType>()
                select this.GenerateCodeTypeDeclaration(complexType, "Facebook.Api");

            return query.Where(type => type != null);
        }

        public CodeCompileUnit GenerateCodeTypeDeclaration(XmlSchemaObject schemaObject, String namespaceName)
        {
            var typeDef = FacebookTypeDefinition.Get(schemaObject, this.BasicTypes);
            if (typeDef.IsCustomType)
            {
                var compileUnit = new CodeCompileUnit();
                var ns = this.GenerateCodeNamespace(namespaceName);

                var codeType = new CodeTypeDeclaration(typeDef.TypeName) { IsClass = true };
                codeType.BaseTypes.Add(new CodeTypeReference(typeof(FacebookObjectBase)));


                var str = Documentation.ResourceManager.GetString(String.Format("{0}__summary", codeType.Name));
                if (!String.IsNullOrEmpty(str)) codeType.Comments.Add(new CodeCommentStatement(String.Format("<summary>{0}</summary>", str), true));

                codeType.CustomAttributes.Add(
                    new CodeAttributeDeclaration("FacebookObjectAttribute",
                        new CodeAttributeArgument(new CodeStringLiteralExpression(typeDef.ApiElementName))));

                var xmlConstructor = new CodeConstructor { Attributes = MemberAttributes.Public };
                xmlConstructor.Parameters.Add(new CodeParameterDeclarationExpression(typeof(XElement), "content"));
                xmlConstructor.BaseConstructorArgs.Add(new CodeVariableReferenceExpression("content"));
                codeType.Members.Add(xmlConstructor);

                var dictConstructor = new CodeConstructor { Attributes = MemberAttributes.Public };
                dictConstructor.Parameters.Add(new CodeParameterDeclarationExpression(typeof(IDictionary<String, Object>), "dict"));
                dictConstructor.BaseConstructorArgs.Add(new CodeVariableReferenceExpression("dict"));
                codeType.Members.Add(dictConstructor);

                codeType.Members.Add(new CodeConstructor { Attributes = MemberAttributes.Public });

                int x = 0;
                foreach (CodeConstructor constructor in codeType.Members)
                {
                    var doc = Documentation.ResourceManager.GetString(String.Format("_FacebookObject_ctor{0}__summary", x.ToString()));
                    if (!String.IsNullOrEmpty(doc)) constructor.Comments.Add(new CodeCommentStatement(String.Format("<summary>{0}</summary>", String.Format(doc, typeDef.TypeName)), true));

                    foreach (CodeParameterDeclarationExpression param in constructor.Parameters)
                    {
                        var paramDoc = Documentation.ResourceManager.GetString(String.Format("_FacebookObject_ctor{0}__param_{1}", x.ToString(), param.Name));
                        if (!String.IsNullOrEmpty(paramDoc)) constructor.Comments.Add(new CodeCommentStatement(String.Format("<param name=\"{0}\">{1}</param>", param.Name, paramDoc), true));
                    }
                    x++;
                }

                codeType.Members.AddRange(this.GenerateCodeTypeMembers(typeDef.Group, typeDef.TypeName));

                ns.Types.Add(codeType);
                compileUnit.Namespaces.Add(ns);
                return compileUnit;
            }
            else return null;
        }

        public CodeTypeMember[] GenerateCodeTypeMembers(XmlSchemaGroupBase group, String typeName)
        {
            var members = new List<CodeTypeMember>();

            foreach (var item in group.Items.OfType<XmlSchemaElement>())
            {
                var typeDef = FacebookTypeDefinition.Get(item, this.BasicTypes);

                var property = new CodeMemberProperty
                {
                    HasGet = true,
                    HasSet = true,                    
                    Attributes = MemberAttributes.Public | MemberAttributes.Final,
                    Type = new CodeTypeReference(typeDef.TypeName),
                    Name = item.Name.ToPascalCase()
                };

                CodeMethodInvokeExpression getExpression = null;
                CodeMethodReferenceExpression getMethod = null;
                String getMethodName = null;
                if (typeDef.Type == null)
                {
                    if (typeDef.IsCollection)
                    {
                        if (typeDef.ChildType.Type == null) getMethodName = "GetFacebookObjectCollection";
                        else if (typeDef.ChildType.Type.IsValueType) getMethodName = "GetValueTypeCollection";
                        else if (typeDef.ChildType.Type == typeof(String)) getMethodName = "GetStringCollection";
                        else throw new InvalidCastException(String.Format("Unexpected child type: {0}", typeDef.ChildType.TypeName));

                        getMethod = new CodeMethodReferenceExpression(new CodeThisReferenceExpression(), getMethodName);
                        getExpression = new CodeMethodInvokeExpression(getMethod, new CodeStringLiteralExpression(item.Name));

                        if (getMethodName != "GetStringCollection") getMethod.TypeArguments.Add(new CodeTypeReference(typeDef.ChildType.TypeName));
                        if (getMethodName != "GetFacebookObjectCollection") getExpression.Parameters.Add(new CodeStringLiteralExpression(typeDef.ChildType.FieldName));
                    }
                    else getMethodName = "GetFacebookObject";
                }
                else if (typeDef.Type.IsValueType) getMethodName = "GetValueType";
                else if (typeDef.Type == typeof(String)) getMethodName = "GetString";
                else throw new InvalidCastException(String.Format("Unexpected type: {0}", typeDef.TypeName));

                if (getExpression == null)
                {
                    getMethod = new CodeMethodReferenceExpression(new CodeThisReferenceExpression(), getMethodName);
                    if (getMethodName != "GetString") getMethod.TypeArguments.Add(new CodeTypeReference(typeDef.TypeName));
                    getExpression = new CodeMethodInvokeExpression(getMethod, new CodeStringLiteralExpression(item.Name));
                }

                property.GetStatements.Add(new CodeMethodReturnStatement(getExpression));
                property.SetStatements.Add(new CodeAssignStatement(
                    new CodeIndexerExpression(new CodePropertyReferenceExpression(new CodeThisReferenceExpression(), "InnerDictionary"), new CodeStringLiteralExpression(item.Name)),
                    new CodePropertySetValueReferenceExpression()));

                  var doc = Documentation.ResourceManager.GetString(String.Format("{0}_{1}__summary",typeName, property.Name));
                  if (!String.IsNullOrEmpty(doc)) property.Comments.Add(new CodeCommentStatement(String.Format("<summary>{0}</summary>", doc), true));
                
                members.Add(property);
            }

            return members.ToArray();
        }

        public IEnumerable<CodeCompileUnit> GenerateClassDeclarations(IDictionary<XmlQualifiedName, XmlSchemaElement> classTypes)
        {
            var compileUnits = new List<CodeCompileUnit>();
            var controllerTypeCompileUnits = new Dictionary<String, CodeCompileUnit>();

            var contextBaseCompileUnit = this.GenerateContext(ApplicationType.Desktop, true);
            compileUnits.AddRange(new CodeCompileUnit[]{
                contextBaseCompileUnit,
                this.GenerateContext(ApplicationType.Desktop, false),
                this.GenerateContext(ApplicationType.Website, false)});
            
            foreach (var element in classTypes.Values.OfType<XmlSchemaElement>())
            {
                var nameParts = element.Name.Split('_');

                var controllerName = String.Format("{0}Controller", nameParts[0].ToPascalCase());

                var responseType = FacebookTypeDefinition.Get(element, this.BasicTypes);

                if (!controllerTypeCompileUnits.ContainsKey(controllerName))
                {
                    var newControllerCompileUnit = this.GenerateControllerTypeDeclaration(controllerName, contextBaseCompileUnit);
                    contextBaseCompileUnit.Namespaces[0].Imports.Add(new CodeNamespaceImport(newControllerCompileUnit.Namespaces[0].Name));

                    controllerTypeCompileUnits.Add(controllerName, newControllerCompileUnit);
                    compileUnits.Add(newControllerCompileUnit);
                }
                CodeCompileUnit controllerCompileUnit = controllerTypeCompileUnits[controllerName];

                controllerCompileUnit.Namespaces[0].Types[0].Members.AddRange(this.GenerateControllerMethods(nameParts[0], nameParts[1], responseType));
            }

            foreach (var controllerCompileUnit in controllerTypeCompileUnits.Values)
            {
                var controller = controllerCompileUnit.Namespaces[0].Types[0];
                if (controller.Members.OfType<CodeTypeMember>().Any(member => member.GetType() == typeof(CodeMemberMethod)))
                {
                    contextBaseCompileUnit.Namespaces[0].Types[0].Members.AddRange(this.GenerateContextMembers(controller.Name, contextBaseCompileUnit));
                }
            }

            return compileUnits;
        }

        public CodeCompileUnit GenerateControllerTypeDeclaration(String controllerName, CodeCompileUnit contextBaseCompileUnit)
        {
            var compileUnit = new CodeCompileUnit();
            var ns = this.GenerateCodeNamespace("Facebook.Api.Controllers");
            var controller = new CodeTypeDeclaration(controllerName) { IsClass = true };
            controller.BaseTypes.Add(new CodeTypeReference("FacebookApiController"));

            var constructor = new CodeConstructor() { Attributes = MemberAttributes.Public };
            constructor.Parameters.Add(new CodeParameterDeclarationExpression("IFacebookContext", "facebookContext"));
            constructor.BaseConstructorArgs.Add(new CodeVariableReferenceExpression("facebookContext"));
            controller.Members.Add(constructor);

            ns.Types.Add(controller);
            compileUnit.Namespaces.Add(ns);

            return compileUnit;
        }

        public CodeTypeMember[] GenerateContextMembers(String controllerName, CodeCompileUnit contextBaseCompileUnit)
        {
            var name = controllerName.Replace("Controller", String.Empty);
            var field = new CodeMemberField(controllerName, String.Format("_{0}", name.ToCamelCase()));
            var property = new CodeMemberProperty()
            {
                Name = name,
                Attributes = MemberAttributes.Public,
                Type = new CodeTypeReference(controllerName)
            };
            property.GetStatements.Add(new CodeMethodReturnStatement(new CodeFieldReferenceExpression(new CodeThisReferenceExpression(), field.Name)));

            var initControllers = contextBaseCompileUnit.Namespaces[0].Types[0].Members.OfType<CodeMemberMethod>().Single(method => method.Name == "InitControllers");
            initControllers.Statements.Add(
                new CodeAssignStatement(
                    new CodeFieldReferenceExpression(new CodeThisReferenceExpression(), field.Name),
                    new CodeObjectCreateExpression(field.Type, new CodeThisReferenceExpression())));

            return new CodeTypeMember[] { field, property };
        }

        public CodeTypeMember[] GenerateControllerMethods(String methodBase, String methodName, FacebookTypeDefinition returnType)
        {
            var members = new List<CodeTypeMember>();
            String apiMethod = String.Format("{0}.{1}", methodBase, methodName);

            if (this.MethodSignatures.ContainsKey(apiMethod))
            {
                foreach (MethodDefinition methodDef in this.MethodSignatures[apiMethod])
                {
                    var method = new CodeMemberMethod()
                    {
                        Name = methodDef.Name.Replace(methodBase + ".", String.Empty).CapitalizeFirst(),
                        ReturnType = new CodeTypeReference(String.Format("FacebookResponse<{0}>", returnType.TypeName)),
                        Attributes = MemberAttributes.Public | MemberAttributes.Final
                    };
                    try { method.Parameters.AddRange(methodDef.Parameters.Select(paramDef => paramDef.DeclarationExpression).ToArray()); }
                    catch (NullReferenceException ex) { throw new ApplicationException(String.Format("Method {0}.{1} had a null parameter.", methodBase, methodName), ex); }
                    method.Comments.Add(new CodeCommentStatement(String.Format("<summary>{0}</summary>", methodDef.Description), true));

                    Configuration.FacebookApiGeneratorSection config = Configuration.FacebookApiGeneratorSection.Current;

                    Configuration.MethodDefinitionElement explicitDefinition = null;
                    String excludeKey = String.Format("{0}.{1}", methodBase.ToPascalCase(), methodName.ToPascalCase());
                    if (config.ExplicitMethodDefinitions.Exists(excludeKey))
                        explicitDefinition = config.ExplicitMethodDefinitions.GetMethod(excludeKey);
                    MethodParameterDefinitionElementCollection explicitParams = null;
                    if (explicitDefinition != null && explicitDefinition.Overloads.Count > 0)
                        explicitParams = explicitDefinition.Overloads;
                    if (explicitDefinition!= null && explicitDefinition.Attributes.Count > 0)
                    {
                        foreach(AttributeDefinitionElement attr in explicitDefinition.Attributes)
                        {           
                            foreach (ConstructorParameterElement attrParam in attr.Params)
                            {
                                //Todo: Add more than one attribute argument
                                CodeAttributeDeclaration attribute = new CodeAttributeDeclaration(
                                    new CodeTypeReference(attr.TypeName),new CodeAttributeArgument(
                                        new CodeStringLiteralExpression(attrParam.Value)));
                                method.CustomAttributes.Add(attribute);
                            }
                        }
                    }
                    if (explicitParams != null)
                    {
                        List<String> parameterList = new List<string>();
                        foreach(MethodParameterDefinition param in methodDef.Parameters)
                            parameterList.Add(param.ApiParameterName);
                        foreach (MethodParameterDefinitionElement explicitMethod in explicitParams)
                        {
                            if (explicitMethod.ContainsParameters(parameterList) && 
                                (explicitMethod.ApplicationType != (ApplicationType.Desktop | ApplicationType.Website)))
                            {
                                // FIX ME: Update this to properly generated code
                                method.Statements.Add(new CodeSnippetExpression(
                                    "if ((this.FacebookContext.ApplicationType & ApplicationType." 
                                    + explicitMethod.ApplicationType.ToString() + ")!= ApplicationType." 
                                    + explicitMethod.ApplicationType.ToString() + 
                                    ")throw new InvalidOperationException(\"This overload cannot be called in this context\")"));
                            }
                        }
                    }
                    method.Statements.Add(new CodeVariableDeclarationStatement(
                        new CodeTypeReference(typeof(Dictionary<String, Object>)), "args",
                        new CodeObjectCreateExpression(typeof(Dictionary<String, Object>))));

                    foreach (var arg in methodDef.Parameters)
                    {
                        method.Comments.Add(new CodeCommentStatement(String.Format("<param name=\"{0}\">{1}</param>", arg.ApiParameterName.ToCamelCase(), arg.Description), true));

                        method.Statements.Add(new CodeMethodInvokeExpression(
                            new CodeMethodReferenceExpression(new CodeVariableReferenceExpression("args"), "Add"),
                            new CodeStringLiteralExpression(arg.ApiParameterName),
                            new CodeVariableReferenceExpression(arg.DeclarationExpression.Name)));
                    }

                    var responseInvokeArgs = new List<CodeExpression>
                    {
                        new CodeStringLiteralExpression(String.Format("{0}.{1}", methodBase.ToPascalCase(), methodName)),
                        new CodeVariableReferenceExpression("args")
                    };

                    method.Statements.Add(new CodeVariableDeclarationStatement("var", "response",
                        new CodeMethodInvokeExpression(
                            new CodeMethodReferenceExpression(new CodeThisReferenceExpression(), "ExecuteRequest", new CodeTypeReference(returnType.TypeName)),
                            responseInvokeArgs.ToArray())));

                    method.Statements.Add(new CodeMethodReturnStatement(new CodeVariableReferenceExpression("response")));

                    members.Add(method);
                }
            }
            return members.ToArray();
        }

        public CodeCompileUnit GenerateContext(ApplicationType appType, Boolean isBase)
        {
            var compileUnit = new CodeCompileUnit();
            CodeNamespace ns = null;
            String name = null;

            if (isBase)
            {
                ns = this.GenerateCodeNamespace("Facebook");
                name = "FacebookContextBase";

            }
            else if (appType == ApplicationType.Desktop)
            {
                ns = this.GenerateCodeNamespace("Facebook.Desktop");
                name = "FacebookDesktopContext";
            }
            else
            {
                ns = this.GenerateCodeNamespace("Facebook.Web");
                name = "FacebookHttpContext";
            }

            var codeType = new CodeTypeDeclaration(name) { IsClass = true };
            
            if (isBase)
            {
                codeType.IsPartial = true;

                var cacheType = new CodeTypeParameter("TCache");
                var sessionType = new CodeTypeParameter("TSession");

                cacheType.Constraints.Add("ICacheWrapper");
                cacheType.Constraints.Add("new()");
                codeType.TypeParameters.Add(cacheType);


                sessionType.Constraints.Add(" class");
                sessionType.Constraints.Add("ISessionInfo");
                codeType.TypeParameters.Add(sessionType);

            }
            else if (appType == ApplicationType.Desktop)
            {
                codeType.BaseTypes.Add("FacebookContextBase<StaticDictionaryCache, Facebook.Api.SessionInfo>");
            }
            else
            {
                codeType.BaseTypes.Add("FacebookContextBase<HttpCache, Facebook.Web.FacebookHttpSession>");
            }

            var initControllersStatement = new CodeMethodInvokeExpression(new CodeThisReferenceExpression(), "InitControllers");
            var appTypeParameterExpression = new CodeFieldReferenceExpression(new CodeTypeReferenceExpression("ApplicationType"), appType.ToString());
            var appTypeAssignmentStatement = new CodeAssignStatement(
                new CodePropertyReferenceExpression(new CodeThisReferenceExpression(), "ApplicationType"),
                new CodeVariableReferenceExpression("appType"));

            if (isBase)
            {
                codeType.Members.Add(new CodeMemberMethod { Name = "InitControllers" });
            }

            var noVersionConstructor = new CodeConstructor { Attributes = MemberAttributes.Public };
            var noVersionConstructorArgsCollection = isBase ? noVersionConstructor.ChainedConstructorArgs : noVersionConstructor.BaseConstructorArgs;
            if (isBase)
            {
                noVersionConstructor.Statements.Add(initControllersStatement);
                noVersionConstructor.Statements.Add(appTypeAssignmentStatement);
                noVersionConstructor.Parameters.Add(new CodeParameterDeclarationExpression("ApplicationType", "appType"));
            }
            else
            {
                noVersionConstructor.BaseConstructorArgs.Add(appTypeParameterExpression);
            }
            noVersionConstructor.Parameters.AddRange(new CodeParameterDeclarationExpression[] {
                new CodeParameterDeclarationExpression("String", "apiKey"),
                new CodeParameterDeclarationExpression("String", "secret")});
            noVersionConstructorArgsCollection.AddRange(new CodeExpression[]{
                new CodeVariableReferenceExpression("apiKey"),
                new CodeVariableReferenceExpression("secret")});
            
            codeType.Members.Add(noVersionConstructor);

            var versionConstructor = new CodeConstructor { Attributes = MemberAttributes.Public };
            var versionConstructorArgsCollection = isBase ? versionConstructor.ChainedConstructorArgs : versionConstructor.BaseConstructorArgs;
            if (isBase)
            {
                versionConstructor.Statements.Add(initControllersStatement);
                versionConstructor.Statements.Add(appTypeAssignmentStatement);
                versionConstructor.Parameters.Add(new CodeParameterDeclarationExpression("ApplicationType", "appType"));
            }
            else
            {
                versionConstructor.BaseConstructorArgs.Add(appTypeParameterExpression);
            }
            versionConstructor.Parameters.AddRange(new CodeParameterDeclarationExpression[] {
                new CodeParameterDeclarationExpression("String", "apiKey"),
                new CodeParameterDeclarationExpression("String", "secret"),
                new CodeParameterDeclarationExpression("String", "version")});
            versionConstructorArgsCollection.AddRange(new CodeExpression[]{
                new CodeVariableReferenceExpression("apiKey"),
                new CodeVariableReferenceExpression("secret"),
                new CodeVariableReferenceExpression("version")});
            codeType.Members.Add(versionConstructor);

            ns.Types.Add(codeType);
            compileUnit.Namespaces.Add(ns);

            return compileUnit;
        }
    }
